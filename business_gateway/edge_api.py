class PostgresEdgeRepository:
    """Small explicit PostgreSQL adapter for the direct-ingest pilot tables."""

    def __init__(self, database_url: str) -> None:
        self.database_url = database_url.strip()
        if not self.database_url:
            raise ValueError("GOOD_BADMINTON_BUSINESS_DATABASE_URL is required")

    def _connect(self):
        import psycopg
        from psycopg.rows import dict_row

        return psycopg.connect(self.database_url, row_factory=dict_row, autocommit=True)

    def _one(self, query: str, params: tuple[Any, ...]) -> dict[str, Any] | None:
        with self._connect() as connection, connection.cursor() as cursor:
            cursor.execute(query, params)
            return cursor.fetchone()

    def binding(self, device_id: str, camera_id: str) -> dict[str, Any] | None:
        return self._one(
            """select d.id::text as device_id, d.venue_id::text as venue_id, d.court_id::text as device_court_id,
                      d.credential_version, d.status as device_status, c.id::text as camera_id,
                      c.court_id::text as court_id, c.status as camera_status,
                      cal.id::text as calibration_id, cal.court_corners
               from business.edge_devices d
               join business.cameras c on c.edge_device_id=d.id
               left join lateral (
                   select id, court_corners from business.camera_calibrations
                   where camera_id=c.id and quality_status='validated'
                   order by version desc limit 1
               ) cal on true
               where d.id=%s and c.id=%s""",
            (device_id, camera_id),
        )

    def claim_nonce(self, device_id: str, nonce: str, expires_at: datetime) -> bool:
        with self._connect() as connection, connection.cursor() as cursor:
            cursor.execute("delete from business.edge_request_nonces where expires_at < now()")
            try:
                cursor.execute(
                    "insert into business.edge_request_nonces (edge_device_id, nonce, expires_at) values (%s, %s, %s)",
                    (device_id, nonce, expires_at),
                )
            except Exception as exc:
                if getattr(exc, "sqlstate", None) == "23505":
                    return False
                raise
        return True

    def heartbeat(self, binding: dict[str, Any], payload: dict[str, Any]) -> None:
        with self._connect() as connection, connection.cursor() as cursor:
            cursor.execute(
                """update business.edge_devices set status='online', last_heartbeat_at=now(),
                          disk_free_bytes=%s, agent_version=%s where id=%s and status <> 'disabled'""",
                (payload["disk_free_bytes"], payload["agent_version"], binding["device_id"]),
            )
            cursor.execute(
                """update business.cameras set status='active', last_heartbeat_at=now()
                   where id=%s and edge_device_id=%s and status <> 'disabled'""",
                (binding["camera_id"], binding["device_id"]),
            )

    def capture_control(self, binding: dict[str, Any]) -> dict[str, Any]:
        """Return the latest server-owned instruction for this bound court.

        A missing row is intentionally safe: newly registered cameras stay in
        heartbeat-only mode until an operator explicitly opens preview or
        capture from the business console.
        """

        row = self._one(
            """select desired_mode, revision, updated_at
               from business.edge_capture_controls where court_id=%s""",
            (binding["court_id"],),
        )
        if not row:
            return {"mode": "idle", "revision": 0, "updated_at": None}
        return {
            "mode": str(row["desired_mode"]),
            "revision": int(row["revision"]),
            "updated_at": str(row["updated_at"]),
        }

    def create_session(self, binding: dict[str, Any], configuration: dict[str, Any]) -> dict[str, Any]:
        session_id = str(uuid.uuid4())
        with self._connect() as connection, connection.cursor() as cursor:
            try:
                cursor.execute(
                    """insert into business.edge_ingest_sessions
                       (id, venue_id, court_id, camera_id, edge_device_id, calibration_id, configuration)
                       values (%s, %s, %s, %s, %s, %s, %s::jsonb)""",
                    (
                        session_id, binding["venue_id"], binding["court_id"], binding["camera_id"],
                        binding["device_id"], binding["calibration_id"], json.dumps(configuration, ensure_ascii=False),
                    ),
                )
            except Exception as exc:
                if getattr(exc, "sqlstate", None) == "23505":
                    raise ValueError("camera already has an active edge ingest session") from exc
                raise
        return self.session(session_id) or {}

    def session(self, session_id: str) -> dict[str, Any] | None:
        return self._one(
            """select s.id::text as id, s.venue_id::text as venue_id, s.court_id::text as court_id,
                      s.camera_id::text as camera_id, s.edge_device_id::text as device_id,
                      s.calibration_id::text as calibration_id, s.status, s.gpu_analysis_session_id,
                      s.gpu_status, s.configuration, s.received_segment_count, s.forwarded_segment_count,
                      s.last_segment_index, s.last_received_at, s.last_forwarded_at, s.error_code, s.error_message,
                      s.gpu_forwarding_enabled, s.preview_available, s.last_preview_at, s.gpu_event_cursor,
                      cal.court_corners
               from business.edge_ingest_sessions s
               left join business.camera_calibrations cal on cal.id=s.calibration_id
               where s.id=%s""",
            (session_id,),
        )

    def receive_segment(self, session: dict[str, Any], metadata: dict[str, Any]) -> dict[str, Any]:
        with self._connect() as connection, connection.cursor() as cursor:
            cursor.execute(
                """select id::text, sha256, idempotency_key, status, gpu_receipt
                   from business.edge_ingest_segments where edge_ingest_session_id=%s and segment_index=%s""",
                (session["id"], metadata["segment_index"]),
            )
            existing = cursor.fetchone()
            if existing:
                if existing["sha256"] != metadata["sha256"] or existing["idempotency_key"] != metadata["idempotency_key"]:
                    raise ValueError("segment index conflicts with a different hash or idempotency key")
                return {**existing, "reused": True}
            segment_id = str(uuid.uuid4())
            cursor.execute(
                """insert into business.edge_ingest_segments
                   (id, edge_ingest_session_id, segment_index, source_start_time_sec, duration_sec, sha256,
                    content_type, content_length_bytes, idempotency_key)
                   values (%s, %s, %s, %s, %s, %s, %s, %s, %s)""",
                (segment_id, session["id"], metadata["segment_index"], metadata["source_start_time_sec"],
                 metadata["duration_sec"], metadata["sha256"], metadata["content_type"],
                 metadata["content_length_bytes"], metadata["idempotency_key"]),
            )
            cursor.execute(
                """update business.edge_ingest_sessions set status='receiving',
                          received_segment_count=received_segment_count+1, last_segment_index=%s,
                          last_received_at=now(), error_code=null, error_message=null where id=%s""",
                (metadata["segment_index"], session["id"]),
            )
        return {"id": segment_id, "status": "received", "reused": False, "gpu_receipt": {}}

    def mark_forwarded(self, session_id: str, segment_index: int, receipt: dict[str, Any], gpu_session_id: str) -> None:
        with self._connect() as connection, connection.cursor() as cursor:
            cursor.execute(
                """update business.edge_ingest_segments set status='forwarded', gpu_receipt=%s::jsonb,
                          forwarded_at=now(), error_code=null, error_message=null
                   where edge_ingest_session_id=%s and segment_index=%s""",
                (json.dumps(receipt, ensure_ascii=False), session_id, segment_index),
            )
            cursor.execute(
                """update business.edge_ingest_sessions set status='processing', gpu_analysis_session_id=%s,
                          gpu_status='accepted', forwarded_segment_count=(select count(*) from business.edge_ingest_segments
                              where edge_ingest_session_id=%s and status='forwarded'), last_forwarded_at=now(),
                          error_code=null, error_message=null where id=%s""",
                (gpu_session_id, session_id, session_id),
            )

    def mark_segment_failed(self, session_id: str, segment_index: int, message: str) -> None:
        with self._connect() as connection, connection.cursor() as cursor:
            cursor.execute(
                """update business.edge_ingest_segments set status='failed', error_code='gpu_forward_failed', error_message=%s
                   where edge_ingest_session_id=%s and segment_index=%s""",
                (message[:1000], session_id, segment_index),
            )
            cursor.execute(
                """update business.edge_ingest_sessions set status='relaying', error_code='gpu_forward_failed',
                   error_message=%s where id=%s""",
                (message[:1000], session_id),
            )

    def mark_completed(self, session_id: str, gpu_status: str, receipt: dict[str, Any]) -> None:
        status_map = {"finalized": "succeeded", "partial": "partial", "cancelled": "cancelled", "failed": "failed"}
        status = status_map.get(gpu_status, "processing")
        with self._connect() as connection, connection.cursor() as cursor:
            cursor.execute(
                """update business.edge_ingest_sessions set status=%s, gpu_status=%s,
                          finished_at=case when %s in ('succeeded', 'partial', 'failed', 'cancelled') then now() else null end,
                          error_code=case when %s='failed' then 'gpu_completion_failed' else null end,
                          error_message=case when %s='failed' then %s else null end where id=%s""",
                (status, gpu_status, status, status, status, json.dumps(receipt, ensure_ascii=False)[:1000], session_id),
            )

    def mark_preview_available(self, session_id: str) -> None:
        with self._connect() as connection, connection.cursor() as cursor:
            cursor.execute(
                """update business.edge_ingest_sessions set preview_available=true, last_preview_at=now(),
                          status=case when status='requested' then 'receiving' else status end where id=%s""",
                (session_id,),
            )

    def record_gpu_events(self, session_id: str, response: dict[str, Any]) -> None:
        events = response.get("events") or []
        if not isinstance(events, list):
            events = []
        with self._connect() as connection, connection.cursor() as cursor:
            for event in events:
                if not isinstance(event, dict):
                    continue
                event_id = str(event.get("event_id") or uuid.uuid4())
                raw_level = str(event.get("level") or "info").lower()
                level = raw_level if raw_level in {"debug", "info", "warning", "error"} else "info"
                cursor.execute(
                    """insert into business.edge_ingest_event_logs
                       (id, edge_ingest_session_id, source, event_id, level, event_type, message, payload)
                       values (%s, %s, 'gpu', %s, %s, %s, %s, %s::jsonb)
                       on conflict (edge_ingest_session_id, source, event_id) do nothing""",
                    (str(uuid.uuid4()), session_id, event_id, level, str(event.get("event_type") or event.get("type") or "gpu_event"),
                     str(event.get("message") or "")[:2000], json.dumps(event, ensure_ascii=False)),
                )
            cursor.execute(
                "update business.edge_ingest_sessions set gpu_event_cursor=%s where id=%s",
                (response.get("next_cursor"), session_id),
            )


class StreamSessionGpuRelay:
    """Temporary-disk relay that uses the existing receipt-aware GPU client."""

    def __init__(self, staging_root: Path, *, config: StreamClientConfig | None = None) -> None:
        self.staging_root = Path(staging_root)
        self.config = config

    def forward(self, session: dict[str, Any], metadata: dict[str, Any], segment_bytes: bytes) -> tuple[str, dict[str, Any]]:
        expected_hash = hashlib.sha256(segment_bytes).hexdigest()
        if expected_hash != metadata["sha256"] or len(segment_bytes) != metadata["content_length_bytes"]:
            raise ValueError("segment bytes do not match declared hash or length")
        session_root = self.staging_root / session["id"]
        session_root.mkdir(parents=True, exist_ok=True)
        extension = ".mp4" if metadata["content_type"] == "video/mp4" else ".m4s"
        segment_path = session_root / f"{metadata['segment_index']:08d}{extension}"
        if segment_path.exists() and hashlib.sha256(segment_path.read_bytes()).hexdigest() != expected_hash:
            raise ValueError("staging path already contains a different segment")
        if not segment_path.exists():
            segment_path.write_bytes(segment_bytes)
        client = StreamSessionClient(
            self.config or StreamClientConfig.from_environment(),
            DeliveryLedger(session_root / "delivery-ledger.json"),
        )
        create_request = validate_create_request({
            "schema_version": "stream-session.v1",
            "camera_id": session["camera_id"],
            "calibration_id": session["calibration_id"],
            "court_corners": session["court_corners"],
            "analysis_mode": "person_only",
            "client_reference": session["id"],
            "configuration": session["configuration"],
        })
        created = client.create_session(create_request, idempotency_key=f"edge-session-{session['id']}")
        gpu_session_id = str(created["analysis_session_id"])
        safe_metadata = dict(metadata)
        safe_metadata["court_corners"] = session["court_corners"]
        receipt = client.submit_segment(segment_path, SegmentMetadata(**safe_metadata))
        segment_path.unlink(missing_ok=True)
        # Keep the ledger but remove an empty raw-video staging leaf where the
        # OS allows it.  Ledger records are non-video operational evidence.
        if not any(path.suffix in {".mp4", ".m4s"} for path in session_root.iterdir()):
            pass
        return gpu_session_id, receipt

    def complete(self, session: dict[str, Any], expected_last_segment_index: int, allow_partial: bool) -> dict[str, Any]:
        session_root = self.staging_root / session["id"]
        client = StreamSessionClient(
            self.config or StreamClientConfig.from_environment(),
            DeliveryLedger(session_root / "delivery-ledger.json"),
        )
        return client.complete(expected_last_segment_index, allow_partial=allow_partial)

    def events(self, session: dict[str, Any], cursor: str | None, limit: int) -> dict[str, Any]:
        session_root = self.staging_root / session["id"]
        client = StreamSessionClient(
            self.config or StreamClientConfig.from_environment(),
            DeliveryLedger(session_root / "delivery-ledger.json"),
        )
        return client.read_events(cursor=cursor, limit=limit)


def _http_error(status: int, message: str) -> HTTPException:
    return HTTPException(status_code=status, detail={"code": "edge_ingest_rejected", "message": message})


def create_edge_app(
    repository: EdgeRepository,
    relay: GpuRelay,
    *,
    edge_master_key: str | None = None,
    preview_store: RollingPreviewStore | None = None,
    recording_store: SessionRecordingStore | None = None,
) -> FastAPI:
    """Create the deployable ingress app; callers inject DB and GPU adapters."""

    master_key = (edge_master_key or os.environ.get("GOOD_BADMINTON_EDGE_MASTER_KEY", "")).strip()
    if len(master_key.encode("utf-8")) < 32:
        raise ValueError("GOOD_BADMINTON_EDGE_MASTER_KEY must contain at least 32 bytes")
    app = FastAPI(title="Good-Badminton Edge Ingest Gateway", version="1.0")

    def authenticate_operator(key: str) -> None:
        if not hmac.compare_digest(key, master_key):
            raise _http_error(403, "operator request is not authorized")

    def authenticate(
        *, method: str, path: str, device_id: str, camera_id: str, payload: dict[str, Any],
        timestamp: str, nonce: str, digest: str, signature: str, segment_bytes: bytes | None = None,
    ) -> dict[str, Any]:
        if payload.get("device_id") != device_id:
            raise _http_error(403, "path device_id does not match payload")
        if payload.get("timestamp") != timestamp or payload.get("nonce") != nonce:
            raise _http_error(401, "signed timestamp or nonce does not match request body")
        computed_digest = payload_sha256(payload, segment_bytes)
        if computed_digest != digest:
            raise _http_error(401, "payload hash does not match request body")
        binding = repository.binding(device_id, camera_id)
        if not binding or binding.get("device_status") == "disabled" or binding.get("camera_status") == "disabled":
            raise _http_error(403, "device/camera binding is not enabled")
        try:
            request_time = verify_request(
                secret=derive_device_secret(master_key, device_id, str(binding["credential_version"])),
                method=method, path=path, timestamp=timestamp, nonce=nonce, digest=digest, signature=signature,
            )
        except EdgeContractError as exc:
            raise _http_error(401, str(exc)) from exc
        if not repository.claim_nonce(device_id, nonce, nonce_expiry(request_time)):
            raise _http_error(409, "edge nonce was already used")
        return binding

