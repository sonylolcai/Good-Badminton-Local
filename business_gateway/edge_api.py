    @app.post("/api/v1/edge/devices/{device_id}/sessions", status_code=202)
    def start_session(
        device_id: str, body: dict[str, Any],
        x_edge_timestamp: str = Header(..., alias=EDGE_TIMESTAMP_HEADER),
        x_edge_nonce: str = Header(..., alias=EDGE_NONCE_HEADER),
        x_edge_payload_sha256: str = Header(..., alias=EDGE_PAYLOAD_SHA256_HEADER),
        x_edge_signature: str = Header(..., alias=EDGE_SIGNATURE_HEADER),
    ):
        try:
            payload = validate_session_start(body)
            binding = authenticate(method="POST", path=f"/api/v1/edge/devices/{device_id}/sessions", device_id=device_id,
                camera_id=payload["camera_id"], payload=payload, timestamp=x_edge_timestamp, nonce=x_edge_nonce,
                digest=x_edge_payload_sha256, signature=x_edge_signature)
            capture_mode = repository.capture_control(binding).get("mode")
            if capture_mode == "idle":
                raise ValueError("business server has not enabled capture for this court")
            if binding.get("calibration_id"):
                # Validate the exact anonymous GPU configuration before
                # creating an analysis-ready business session.
                normalized_configuration = validate_create_request({
                    "schema_version": "stream-session.v1",
                    "camera_id": binding["camera_id"],
                    "calibration_id": binding["calibration_id"],
                    "court_corners": binding["court_corners"],
                    "analysis_mode": "person_only",
                    "client_reference": f"edge-config-{device_id}",
                    "configuration": payload["configuration"],
                })["configuration"]
                ingest_mode = "analysis_ready"
            else:
                # A signed terminal can establish a short preview so the
                # operator can mark the four real image corners. It remains
                # impossible to relay this session to GPU.
                if capture_mode != "preview":
                    raise ValueError("camera has no validated calibration; start preview, save four corners, then start record")
                normalized_configuration = validate_configuration(payload["configuration"])
                ingest_mode = "preview_only"
            session = repository.create_session(binding, normalized_configuration)
        except EdgeContractError as exc:
            raise _http_error(422, str(exc)) from exc
        except ValueError as exc:
            raise _http_error(409, str(exc)) from exc
        return {"status": "accepted", "edge_ingest_session_id": session["id"], "court_id": session["court_id"], "ingest_mode": ingest_mode,
                "delivery_mode": "preview_only" if ingest_mode == "preview_only" else "business_to_gpu_direct"}

    @app.post("/api/v1/edge/sessions/{session_id}/segments/{segment_index}", status_code=202)
    async def upload_segment(
        session_id: str, segment_index: int, segment: UploadFile = File(...), metadata: str = Form(...),
        x_edge_timestamp: str = Header(..., alias=EDGE_TIMESTAMP_HEADER),
        x_edge_nonce: str = Header(..., alias=EDGE_NONCE_HEADER),
        x_edge_payload_sha256: str = Header(..., alias=EDGE_PAYLOAD_SHA256_HEADER),
        x_edge_signature: str = Header(..., alias=EDGE_SIGNATURE_HEADER),
    ):
        try:
            envelope = validate_segment_envelope(json.loads(metadata))
            if envelope["segment"].get("segment_index") != segment_index:
                raise EdgeContractError("path segment_index does not match metadata")
            stored = repository.session(session_id)
            if not stored:
                raise _http_error(404, "edge ingest session was not found")
            if stored["device_id"] != envelope["device_id"] or stored["camera_id"] != envelope["camera_id"]:
                raise _http_error(403, "session does not belong to this device/camera")
            video = await segment.read()
            binding = authenticate(method="POST", path=f"/api/v1/edge/sessions/{session_id}/segments/{segment_index}",
                device_id=envelope["device_id"], camera_id=envelope["camera_id"], payload=envelope,
                timestamp=x_edge_timestamp, nonce=x_edge_nonce, digest=x_edge_payload_sha256,
                signature=x_edge_signature, segment_bytes=video)
            del binding  # Binding check occurs before any GPU/network action.
            segment_metadata = validate_segment_metadata(envelope["segment"])
            if hashlib.sha256(video).hexdigest() != segment_metadata["sha256"] or len(video) != segment_metadata["content_length_bytes"]:
                raise EdgeContractError("segment bytes do not match metadata")
            if stored.get("calibration_id") and segment_metadata["court_corners"] != stored["court_corners"]:
                raise EdgeContractError("terminal court_corners do not match the server-validated calibration")
            record = repository.receive_segment(stored, segment_metadata)
            if recording_store:
                recording_store.store(session_id, segment_index, segment_metadata["content_type"], video)
            if record["status"] == "forwarded":
                return {"status": "accepted", "reused": True, "gpu_receipt": record["gpu_receipt"]}
            if preview_store:
                preview_store.store(session_id, segment_index, segment_metadata["content_type"], video)
                if hasattr(repository, "mark_preview_available"):
                    repository.mark_preview_available(session_id)
            # GPU delivery is controlled per case by an operator.  Video keeps
            # arriving at the business gateway for the live preview while this
            # flag is off; only future segments are forwarded after it is on.
            if not stored.get("calibration_id"):
                return {
                    "status": "preview_available",
                    "reused": bool(record["reused"]),
                    "edge_ingest_session_id": session_id,
                    "gpu_forwarding": "blocked_pending_calibration",
                    "message": "视频预览已更新；请先在业务后台保存并验证球场四角，才可开启 GPU 推送。",
                }
            if not bool(stored.get("gpu_forwarding_enabled", True)):
                return {
                    "status": "preview_available",
                    "reused": bool(record["reused"]),
                    "edge_ingest_session_id": session_id,
                    "gpu_forwarding": "paused",
                    "message": "视频预览已更新；GPU 推送由运营后台开启后才会处理后续片段。",
                }
            gpu_session_id, receipt = relay.forward(stored, segment_metadata, video)
            repository.mark_forwarded(session_id, segment_index, receipt, gpu_session_id)
            return {"status": "accepted", "reused": bool(record["reused"]), "gpu_analysis_session_id": gpu_session_id, "gpu_receipt": receipt}
        except HTTPException:
            raise
        except (EdgeContractError, ValueError, json.JSONDecodeError) as exc:
            raise _http_error(422, str(exc)) from exc
        except Exception as exc:
            try:
                repository.mark_segment_failed(session_id, segment_index, str(exc))
            except Exception:
                pass
            raise _http_error(502, "business gateway did not receive a GPU receipt; retry the same segment") from exc

    @app.post("/api/v1/edge/sessions/{session_id}/complete", status_code=202)
    def complete_session(
        session_id: str, body: dict[str, Any],
        x_edge_timestamp: str = Header(..., alias=EDGE_TIMESTAMP_HEADER),
        x_edge_nonce: str = Header(..., alias=EDGE_NONCE_HEADER),
        x_edge_payload_sha256: str = Header(..., alias=EDGE_PAYLOAD_SHA256_HEADER),
        x_edge_signature: str = Header(..., alias=EDGE_SIGNATURE_HEADER),
    ):
        try:
            payload = validate_complete_envelope(body)
            stored = repository.session(session_id)
            if not stored:
                raise _http_error(404, "edge ingest session was not found")
            if stored["device_id"] != payload["device_id"] or stored["camera_id"] != payload["camera_id"]:
                raise _http_error(403, "session does not belong to this device/camera")
            authenticate(method="POST", path=f"/api/v1/edge/sessions/{session_id}/complete", device_id=payload["device_id"],
                camera_id=payload["camera_id"], payload=payload, timestamp=x_edge_timestamp, nonce=x_edge_nonce,
                digest=x_edge_payload_sha256, signature=x_edge_signature)
            recording = (
                recording_store.complete(session_id, payload["expected_last_segment_index"])
                if recording_store else {"status": "not_configured"}
            )
            # A pilot court is allowed to stop a capture before the operator
            # enables GPU forwarding.  It has no upstream GPU session to
            # complete, but the edge session must still leave the active-set
            # so a restarted venue relay can start a new capture.
            if (not bool(stored.get("gpu_forwarding_enabled", True))
                    and not stored.get("gpu_analysis_session_id")):
                receipt = {"status": "cancelled", "reason": "gpu_forwarding_was_not_enabled"}
                repository.mark_completed(session_id, "cancelled", receipt)
                return {"status": "accepted", "edge_ingest_session_id": session_id,
                        "gpu_status": "cancelled", "gpu_receipt": receipt, "recording": recording}
            receipt = relay.complete(stored, payload["expected_last_segment_index"], payload["allow_partial"])
            gpu_status = str(receipt.get("status") or "processing")
            repository.mark_completed(session_id, gpu_status, receipt)
            return {"status": "accepted", "edge_ingest_session_id": session_id, "gpu_status": gpu_status,
                    "gpu_receipt": receipt, "recording": recording}
        except HTTPException:
            raise
        except (EdgeContractError, ValueError) as exc:
            raise _http_error(422, str(exc)) from exc
        except Exception as exc:
            raise _http_error(502, "business gateway could not complete the GPU session; retry the same completion request") from exc

