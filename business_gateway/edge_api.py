    @app.get("/api/v1/edge/sessions/{session_id}/gpu-events")
    def gpu_events(session_id: str, limit: int = 100):
        session = repository.session(session_id)
        if not session:
            raise _http_error(404, "edge ingest session was not found")
        if not session.get("gpu_analysis_session_id"):
            return {"case_id": session_id, "gpu_analysis_session_id": None, "events": [], "next_cursor": None,
                    "message": "尚未向 GPU 推送片段。"}
        response = relay.events(session, session.get("gpu_event_cursor") or None, max(1, min(limit, 500)))
        if hasattr(repository, "record_gpu_events"):
            repository.record_gpu_events(session_id, response)
        return {"case_id": session_id, "gpu_analysis_session_id": session["gpu_analysis_session_id"], **response}

